# 붙어 있어도 같은 곳을 가리키는 꼬리말
_SUFFIXES = ("특별자치시", "특별자치도", "특별시", "광역시", "자치시", "자치도",
             "시청", "역", "시", "도", "군")


def _aliases() -> dict:
    """'마포구' → '마포', '수원' → '수원시' 처럼 부르는 대로 다 찾히게."""
    table = {}
    for key, value in PLACES.items():
        names = {key}
        if key.endswith("구"):
            names.add(key[:-1])          # 마포구 → 마포
        else:
            names.add(key + "시")        # 수원 → 수원시
            names.add(key + "구")        # 중구 같은 경우 대비
        for n in names:
            table.setdefault(n, value)
    return table


_ALIASES = _aliases()


def _strip(word: str) -> str:
    for suffix in _SUFFIXES:
        if len(word) > len(suffix) + 1 and word.endswith(suffix):
            return word[:-len(suffix)]
    return word


def find(text: str):
    """'서울시 마포구' 같은 말에서 가장 구체적인 지명을 찾는다. 없으면 None."""
    text = (text or "").strip()
    if not text:
        return None

    best = None  # (이름 길이, 좌표)
    for word in [text] + text.split():
        for candidate in (word, _strip(word)):
            hit = _ALIASES.get(candidate)
            # 더 구체적인 이름(긴 쪽)을 고른다 — '서울시 마포구' 면 마포구
            if hit and (best is None or len(candidate) >= best[0]):
                best = (len(candidate), hit)
    return best[1] if best else None
